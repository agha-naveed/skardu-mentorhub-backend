// Generates docs/API.md by reading the route code, so the reference
// always lists exactly what exists.   node scripts/routes.mjs
import fs from 'fs';

const files = ['server.js', ...fs.readdirSync('routes').filter((f) => f.endsWith('.js') && f !== 'index.js').map((f) => `routes/${f}`)];
const re = /\b(?:app|router)\.(get|post|put|patch|delete)\(\s*'([^']+)'/g;
const rows = [];

for (const file of files) {
  const src = fs.readFileSync(file, 'utf8');
  let m;
  while ((m = re.exec(src))) {
    const window = src.slice(m.index, m.index + 260).split('handle(')[0];
    const roles = window.match(/requireRole\(([^)]*)\)/);
    const who = roles ? roles[1].replace(/['\s]/g, '').split(',').join(' / ')
      : /requireLogin/.test(window) ? 'any signed-in user' : 'public';
    rows.push({ method: m[1].toUpperCase(), path: m[2].replace(/\(\[.*?\]\{.*?\}\)/, ''), who, file });
  }
}

const section = (p) => p.startsWith('/api/admin') ? 'Admin' : p.startsWith('/api/tutor') ? 'Tutor'
  : p.startsWith('/api/auth') ? 'Account and sign-in' : p.startsWith('/api/exams') ? 'Exams (student)'
  : p.startsWith('/api/chats') ? 'Chat' : p.startsWith('/api/analytics') ? 'Analytics' : 'Student and shared';

const groups = {};
for (const r of rows) (groups[section(r.path)] ||= []).push(r);

let md = `# API reference\n\n_Generated by \`node scripts/routes.mjs\` — ${rows.length} routes._\n\n`;
md += 'All routes are under the server address and return JSON. Errors are `{ "error": "a sentence a person can read" }`.\n';
md += 'Send `Authorization: Bearer <token>` (from `/api/auth/login`) on everything except the **public** routes.\n\n';
for (const [name, list] of Object.entries(groups).sort()) {
  md += `## ${name}\n\n| Method | Path | Who | File |\n|---|---|---|---|\n`;
  for (const r of list.sort((a, b) => a.path.localeCompare(b.path))) md += `| ${r.method} | \`${r.path}\` | ${r.who} | ${r.file} |\n`;
  md += '\n';
}
md += `## Live events (Socket.IO)\n\nConnect with \`auth: { token }\`.\n\n| Event | Direction | Meaning |\n|---|---|---|\n`
  + '| `notification:new` | server → app | A notification was created; carries `data.route` |\n'
  + '| `chat:join` / `chat:leave` | app → server | Enter or leave a conversation (checked against enrollment) |\n'
  + '| `chat:message` | server → room | A new message |\n'
  + '| `chat:unread` | server → user | A message arrived while on another screen |\n'
  + '| `chat:ack` | app → server | The message reached this phone (second tick) |\n'
  + '| `chat:read` | app → server | The conversation was looked at (blue ticks) |\n'
  + '| `chat:delivered` / `chat:seen` | server → room | Receipt updates for the sender |\n'
  + '| `chat:typing` | both | Typing indicator (never stored) |\n';
fs.writeFileSync('docs/API.md', md);
console.log(`docs/API.md written (${rows.length} routes)`);
